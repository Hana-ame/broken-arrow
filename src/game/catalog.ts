export const UNIT_BY_ID: Record<string, UnitTemplate> = Object.fromEntries(
  UNIT_CATALOG.map((u) => [u.id, u])
);

export function getFactionUnits(faction: FactionId): UnitTemplate[] {
  return UNIT_CATALOG.filter((u) => u.faction === faction);
}

export function createDefaultDeck(faction: FactionId): BattlegroupDeck {
  const units = getFactionUnits(faction);
  const entries = units.map((u) => ({
    templateId: u.id,
    count: Math.min(u.maxStock, u.category === 'armor' || u.category === 'infantry' ? 3 : 2),
  }));
  return {
    id: `default_${faction}`,
    name: faction === 'coalition' ? '1st Combined Arms Task Force' : '4th Guards Mechanized Battlegroup',
    faction,
    specs: ['armored', 'airborne'],
    entries,
  };
}

export function computeDeckCost(deck: BattlegroupDeck): number {
  let total = 0;
  for (const entry of deck.entries) {
    const tpl = UNIT_BY_ID[entry.templateId];
    if (!tpl) continue;
    total += tpl.cost * Math.max(0, entry.count);
  }
  return total;
}

export function validateDeck(deck: BattlegroupDeck): {
  valid: boolean;
  totalCost: number;
  errors: string[];
} {
  const errors: string[] = [];
  const totalCost = computeDeckCost(deck);
  if (totalCost > DECK_BUDGET_LIMIT) {
    errors.push(`Deck exceeds ${DECK_BUDGET_LIMIT} point budget (${totalCost}).`);
  }
  const totalUnits = deck.entries.reduce((acc, e) => acc + Math.max(0, e.count), 0);
  if (totalUnits < 6) {
    errors.push('Battlegroup requires at least 6 units.');
  }
  for (const entry of deck.entries) {
    const tpl = UNIT_BY_ID[entry.templateId];
    if (!tpl) {
      errors.push(`Unknown unit template: ${entry.templateId}`);
      continue;
    }
    if (tpl.faction !== deck.faction) {
      errors.push(`Unit ${tpl.name} does not belong to faction ${deck.faction}.`);
    }
    if (entry.count > tpl.maxStock) {
      errors.push(`${tpl.name} exceeds max availability (${tpl.maxStock}).`);
    }
  }
  return {
    valid: errors.length === 0,
    totalCost,
    errors,
  };
}
